test("concurrent invoice deliveries cannot spend the same stock", async () => {
  const db = await inventoryOwner()
  const org = "a0000000-0000-0000-0000-000000000001"
  const suffix = crypto.randomUUID()
  const warehouse = await db.from("warehouses").select("id").eq("org_id", org).eq("is_default", true).single()
  expect(warehouse.error).toBeNull()
  const product = await db.from("products").insert({ org_id: org, name: `Concurrent stock ${suffix}`, type: "goods", is_stockable: true, cost_satang: 100 }).select("id").single()
  expect(product.error).toBeNull()
  const count = await db.rpc("adjust_stock", { p_org_id: org, p_product_id: product.data!.id, p_warehouse_id: warehouse.data!.id, p_count: 1, p_reason: "Synthetic concurrency fixture", p_key: crypto.randomUUID() })
  expect(count.error).toBeNull()
  const profile = await db.rpc("update_business_profile", { p_org_id: org, p_legal_name: "Synthetic inventory seller", p_business_address: "Synthetic address", p_tax_id: "", p_tax_status: "unknown" })
  expect(profile.error).toBeNull()
  const invoiceIds: string[] = []
  for (let i = 0; i < 2; i++) {
    const invoice = await db.from("invoices").insert({ org_id: org, client_id: "c0000000-0000-0000-0000-000000000001", number: `INV-RACE-${suffix}-${i}` }).select("id").single()
    expect(invoice.error).toBeNull()
    const line = await db.from("invoice_items").insert({ org_id: org, invoice_id: invoice.data!.id, product_id: product.data!.id, description: "Concurrent stock unit", quantity: 1, unit_price_satang: 200 })
    expect(line.error).toBeNull()
    const version = await db.from("invoices").select("version").eq("org_id", org).eq("id", invoice.data!.id).single()
    expect(version.error).toBeNull()
    const issued = await db.rpc("issue_invoice", { p_org_id: org, p_invoice_id: invoice.data!.id, p_expected_version: version.data!.version, p_key: crypto.randomUUID() })
    expect(issued.error).toBeNull()
    invoiceIds.push(invoice.data!.id)
  }
  const results = await Promise.all(invoiceIds.map(id => db.rpc("deliver_invoice", { p_org_id: org, p_invoice_id: id })))
  expect(results.filter(result => !result.error)).toHaveLength(1)
  expect(results.find(result => result.error)?.error?.message).toContain("Insufficient stock")
  const winner = invoiceIds[results.findIndex(result => !result.error)]
  const retries = await Promise.all([1, 2].map(() => db.rpc("deliver_invoice", { p_org_id: org, p_invoice_id: winner })))
  expect(retries.every(result => !result.error)).toBe(true)
  const stock = await db.from("stock_on_hand").select("quantity").eq("org_id", org).eq("product_id", product.data!.id).single()
  expect(stock.error).toBeNull()
  expect(stock.data!.quantity).toBe(0)
  const moves = await db.from("stock_moves").select("id", { count: "exact", head: true }).eq("org_id", org).eq("product_id", product.data!.id).eq("kind", "delivery")
  expect(moves.error).toBeNull()
  expect(moves.count).toBe(1)
})
