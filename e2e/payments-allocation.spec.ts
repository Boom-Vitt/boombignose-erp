import { test, expect } from "@playwright/test"
import { randomUUID } from "node:crypto"
import { financeFixture } from "./finance-fixture"

test("one reviewed transfer settles several invoices and leaves reusable refundable credit", async ({ page, browser }) => {
  const f = await financeFixture()
  const adminEmail = `reviewer-${randomUUID()}@example.invalid`, adminPassword = `Local-${randomUUID()}!`
  const reviewer = await f.admin.auth.admin.createUser({ email: adminEmail, password: adminPassword, email_confirm: true })
  expect(reviewer.error).toBeNull()
  const reviewerId = reviewer.data.user!.id
  expect((await f.admin.from("memberships").insert({ org_id: f.org, user_id: reviewerId, role: "admin" })).error).toBeNull()
  const reviewerContext = await browser.newContext()
  const reviewerPage = await reviewerContext.newPage()
  try {
    const first = await f.invoice(), second = await f.invoice(), third = await f.invoice()
    await f.login(page)
    await page.goto("/settings/finance")
    await page.getByLabel("Require a different staff member to verify reported payments", { exact: true }).check()
    await page.getByRole("button", { name: "Save payment review policy", exact: true }).click()
    await expect.poll(async () => (await f.staff.from("org_settings").select("require_different_payment_reviewer").eq("org_id", f.org).single()).data?.require_different_payment_reviewer).toBe(true)
    await page.goto(`/finance/receipts?client=${f.clientId}`)
    const report = page.locator("form").filter({ has: page.getByRole("button", { name: "Report customer receipt", exact: true }) })
    await report.getByLabel("Receipt amount (THB)", { exact: true }).fill("250.00")
    await report.getByLabel("Receipt report reference", { exact: true }).fill("One transfer for two invoices")
    await report.getByLabel(new RegExp(`Allocate ${first.number}`)).fill("100.00")
    await report.getByLabel(new RegExp(`Allocate ${second.number}`)).fill("100.00")
    await report.getByRole("button", { name: "Report customer receipt", exact: true }).click()
    await expect(page.getByText("One transfer for two invoices", { exact: false })).toBeVisible()
    await page.getByLabel("Verification evidence reference").fill("Verified bank transfer 001")
    await page.getByRole("button", { name: "Verify receipt", exact: true }).click()
    await expect(page.getByText("A different staff member must verify this reported receipt", { exact: true })).toBeVisible()
    expect((await f.staff.from("payments").select("id").eq("org_id", f.org)).data).toHaveLength(0)
    await f.login(reviewerPage, { email: adminEmail, password: adminPassword })
    await reviewerPage.goto(`/finance/receipts?client=${f.clientId}`)
    await reviewerPage.getByLabel("Verification evidence reference").fill("Verified bank transfer 001")
    await reviewerPage.getByRole("button", { name: "Verify receipt", exact: true }).click()
    await expect.poll(async () => (await f.staff.from("client_balances").select("credit_satang").eq("client_id", f.clientId).single()).data?.credit_satang).toBe(5000)
    const csv = await reviewerPage.request.get("/finance/invoices/export")
    expect(csv.ok()).toBe(true)
    const rows = (await csv.text()).split("\n")
    for (const invoice of [first, second]) expect(rows.find(row => row.startsWith(invoice.id))?.split(",")[7]).toBe("100.00")
    const apply = reviewerPage.locator("form").filter({ has: reviewerPage.getByRole("button", { name: "Apply customer credit", exact: true }) })
    await apply.getByLabel(new RegExp(`Allocate ${third.number}`)).fill("20.00")
    await apply.getByRole("button", { name: "Apply customer credit", exact: true }).click()
    await expect.poll(async () => (await f.staff.from("client_balances").select("credit_satang").eq("client_id", f.clientId).single()).data?.credit_satang).toBe(3000)
    await apply.getByLabel(new RegExp(`Allocate ${third.number}`)).fill("20.00")
    await apply.getByRole("button", { name: "Apply customer credit", exact: true }).click()
    await expect.poll(async () => (await f.staff.from("client_balances").select("credit_satang").eq("client_id", f.clientId).single()).data?.credit_satang).toBe(1000)
    await reviewerPage.getByLabel("Refund amount (THB)", { exact: true }).fill("10.00")
    await reviewerPage.getByLabel("Refund bank reference", { exact: true }).fill("Customer refund 001")
    await reviewerPage.getByRole("button", { name: "Refund customer credit", exact: true }).click()
    await expect.poll(async () => (await f.staff.from("client_balances").select("credit_satang").eq("client_id", f.clientId).single()).data?.credit_satang).toBe(0)
    const refund = reviewerPage.locator("div.rounded.border.p-3").filter({ hasText: "Customer refund 001" })
    await refund.getByLabel("Reversal reason", { exact: true }).fill("Incorrect refund posting")
    await refund.getByRole("button", { name: "Reverse receipt", exact: true }).click()
    await expect.poll(async () => (await f.staff.from("client_balances").select("credit_satang").eq("client_id", f.clientId).single()).data?.credit_satang).toBe(1000)
    const receipt = reviewerPage.locator("div.rounded.border.p-3").filter({ hasText: "Verified bank transfer 001" })
    await receipt.getByLabel("Reversal reason", { exact: true }).fill("Bounced customer transfer")
    await receipt.getByRole("button", { name: "Reverse receipt", exact: true }).click()
    await expect.poll(async () => (await f.staff.from("client_balances").select("credit_satang, outstanding_satang").eq("client_id", f.clientId).single()).data).toEqual({ credit_satang: 0, outstanding_satang: 30000 })
    const payments = await f.staff.from("payments").select("amount_satang").eq("org_id", f.org).eq("verification_state", "verified")
    expect(payments.data!.reduce((sum, p) => sum + p.amount_satang, 0)).toBe(0)
    expect((await f.staff.from("invoices").select("status").in("id", [first.id, second.id, third.id])).data?.every(i => i.status === "sent")).toBe(true)
  } finally {
    await reviewerContext.close()
    await f.cleanup()
    expect((await f.admin.auth.admin.deleteUser(reviewerId)).error).toBeNull()
  }
})
