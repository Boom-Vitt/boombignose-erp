import { test, expect } from "@playwright/test"
import { loginDemo } from "./auth"

test("create, confirm, partially receive and bill a purchase order", async ({ page }) => {
  await loginDemo(page)
  const name = `Purchasing smoke ${Date.now()}`
  await page.goto("/vendors/new")
  await page.getByLabel("Name", { exact: true }).fill(name)
  await page.getByLabel("Email", { exact: true }).fill("purchasing-smoke@example.invalid")
  await page.getByRole("button", { name: "Create vendor", exact: true }).click()
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible()
  await page.getByRole("link", { name: "New purchase order", exact: true }).click()
  await page.getByRole("button", { name: "Create purchase order", exact: true }).click()
  await expect(page.getByRole("heading", { name: /^PO-\d{4}-\d+/ })).toBeVisible()
  const number = await page.getByRole("heading", { name: /^PO-/ }).innerText()

  await page.getByRole("combobox", { name: "Product (optional)" }).click()
  await page.getByRole("option").filter({ hasNotText: "Free-text line" }).first().click()
  await expect(page.getByLabel("Unit cost (THB)")).not.toHaveValue("")
  await page.getByLabel("Description", { exact: true }).fill("Smoke purchase line")
  await page.getByLabel("Quantity", { exact: true }).fill("4")
  await page.getByLabel("Unit cost (THB)").fill("12.34")
  await page.getByRole("button", { name: "Add line", exact: true }).click()
  await expect(page.getByRole("row").filter({ hasText: "Smoke purchase line" })).toContainText("49.36")
  await page.getByRole("button", { name: "Confirm", exact: true }).click()
  await expect(page.locator('[aria-label="Purchase status"] [aria-current="step"]')).toHaveText("Confirmed")
  await page.getByLabel("Received total for Smoke purchase line").fill("1.5")
  await page.getByRole("button", { name: "Record receipt", exact: true }).click()
  await expect(page.getByRole("row").filter({ hasText: "Smoke purchase line" })).toContainText("1.5")
  await page.getByRole("button", { name: "Create bill", exact: true }).click()
  const bills = page.getByRole("region", { name: "Vendor bills" })
  await expect(bills).toContainText(`${number}-B1`)
  await expect(bills).toContainText("18.51")
  await page.getByLabel("Received total for Smoke purchase line").fill("4")
  await page.getByRole("button", { name: "Record receipt", exact: true }).click()
  await expect(page.locator('[aria-label="Purchase status"] [aria-current="step"]')).toHaveText("Received")
  await page.getByRole("button", { name: "Create bill", exact: true }).click()
  await expect(page.locator('[aria-label="Purchase status"] [aria-current="step"]')).toHaveText("Billed")
  await expect(bills).toContainText(`${number}-B2`)
  await expect(bills).toContainText("30.85")
  await bills.getByRole("button", { name: "Mark paid", exact: true }).first().click()
  await expect(bills).toContainText("Paid")
  await page.goto("/finance")
  await page.getByRole("tab", { name: "Costs", exact: false }).click()
  await expect(page.getByRole("row").filter({ hasText: `${number}-B1` })).toContainText("Paid")
  await expect(page.getByRole("row").filter({ hasText: `${number}-B2` })).toContainText("Unpaid")
})
