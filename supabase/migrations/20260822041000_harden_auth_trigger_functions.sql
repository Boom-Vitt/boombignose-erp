-- Keep internal auth-trigger functions out of the public API schema and make
-- their search paths deterministic. The workspace RPC remains public because
-- an authenticated browser calls it, but it validates auth.uid() itself.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', new.email))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

revoke all on function public.handle_new_user() from public, anon, authenticated;
revoke all on function private.handle_new_user() from public, anon, authenticated;
